"""Validation for Agent 3 beat HTML (spec §7), in two layers.

- :func:`check_static` (no manimgl): the beats parse, every planned VO line is
  some ``<beat vo=…>``, and the plan's tex/text/bars data is drawn verbatim.
- :func:`check_runtime` (subprocess, needs manimgl + Chromium): builds every
  leaf, runs the Chromium layout and plays the scene with animations skipped.
  Layout overflow, LaTeX errors and bad attributes come back per beat and id.

    uv run --group render --group layout python -m konvey.stage.check out/run/agent3-S1.html
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

from ..schemas import Scene
from . import displays
from . import theme as themes
from .match import attrs_of, squash
from .parse import BeatError, parse_beats, prepare_beats

REPO_ROOT = Path(__file__).resolve().parents[2]

WRAPPER = '''"""Generated by Konvey (renderer=stage). Render: manimgl {name}.py SingleScene -w"""
import sys
from pathlib import Path

sys.path.insert(0, {root!r})
from konvey.stage.scene import StageScene  # noqa: E402


class SingleScene(StageScene):
    beats_file = str(Path(__file__).with_suffix(".html"))
    prelude_file = {prelude}
    theme = {theme!r}
'''


PREVIOUS = {"S2": "S1", "S3": "S2"}


def wrapper_source(html_path: Path, theme: str | None = None) -> str:
    """``agent3-S2.py`` also names ``agent3-S1.html`` so S2 opens on S1's last frame.
    The theme is recorded so a later re-render looks the same."""
    sid = html_path.stem.split("-")[-1]
    prev = PREVIOUS.get(sid)
    prelude = (f'str(Path(__file__).with_name("{html_path.stem.replace(sid, prev)}.html"))'
               if prev else '""')
    return WRAPPER.format(name=html_path.stem, root=str(REPO_ROOT), prelude=prelude,
                          theme=theme or themes.current().name)


MIN_SIZE = {"text": 24, "caption": 24, "h3": 26, "h2": 34, "h1": 44,
            **{d.tag: d.min_size for d in displays.all_displays() if d.min_size}}


def _num(v: str) -> float:
    try:
        return float(v)
    except ValueError:
        return 0.0


def check_static(html: str, scene: Scene) -> list[str]:
    try:
        beats = parse_beats(html)
        prepare_beats(beats)
    except (BeatError, ValueError) as e:
        return [f"parse error: {e}"]
    problems: list[str] = []
    for b in beats if themes.current().letterbox else []:
        box = b.attrs.get("letterbox")
        first, last = b.index == 0, b.index == len(beats) - 1
        if box == "open" and not (scene.id == "S1" and first):
            problems.append(f'beat {b.index}: letterbox="open" only on the first beat of S1 '
                            f"(the scenes play back to back; reopening flashes black)")
        if box == "close" and not (scene.id == "S3" and last):
            problems.append(f'beat {b.index}: letterbox="close" only on the last beat of S3')
    vos = [squash(b.attrs.get("vo", "")) for b in beats]
    for i, beat in enumerate(scene.beats):
        if squash(beat.vo_line) not in vos:
            problems.append(f'plan beat {i}: no <beat vo="{beat.vo_line}"> (copy the vo_line verbatim)')
    leaves = [n for b in beats for n in b.leaves().values()]
    for b in beats:
        for n in b.leaves().values():
            size = n.attrs.get("size")
            floor = MIN_SIZE.get(n.tag)
            if size and floor and _num(size) < floor:
                problems.append(f'beat {b.index} <{n.tag} id={n.id}> size="{size}" is too small to read '
                                f'(min {floor}; size is in px, like a font size); show less instead of shrinking it')
    names = ", ".join(themes.current().color_names())
    for b in beats:
        for n in [*b.leaves().values(), *b.world.values()]:
            if "#" in n.attrs.get("color", ""):
                problems.append(f'beat {b.index} <{n.tag} id={n.id}> color="{n.attrs["color"]}": '
                                f"use a theme colour name ({names}), not hex")
    blob = "\n".join({squash(n.text) for n in leaves if n.tag != "bars"})
    for i, beat in enumerate(scene.beats):
        for obj in beat.objects:
            if isinstance(obj, str):
                continue
            d, tag = obj.data, f"plan beat {i} object {obj.id!r}"
            if obj.kind == "text" and d.get("text") and squash(d["text"]) not in blob:
                problems.append(f"{tag}: text {d['text']!r} not shown in any text/h1-h3/caption")
            disp = displays.for_kind(obj.kind)
            if disp is not None and disp.check_drawn is not None:
                problems += disp.check_drawn(tag, obj, leaves)
    for disp in displays.all_displays():
        if disp.check_scene is not None:
            problems += disp.check_scene(scene, beats)
    return problems


def apply_plan_state(html: str, scene: Scene) -> str:
    """Copy each beat's planned state into Agent 3's tags, for displays whose state the plan
    fully gives (a system's parts, holds and items); everything Agent 3 chose about the look
    stays. Weak models dropped held values again and again even when told the exact tag.
    A beat's planned ``camera`` (view, zoom, focus, shot) is written on its ``<beat>`` the same way."""
    html = _apply_cameras(html, scene)
    for beat in scene.beats:
        objs = [(o, displays.for_kind(o.kind)) for o in beat.objects if not isinstance(o, str)]
        objs = [(o, d) for o, d in objs if d is not None and d.apply_plan is not None]
        if not objs:
            continue
        for m in re.finditer(r"<beat\b([^>]*)>(.*?)</beat>", html, re.S):
            if squash(attrs_of(m.group(1)).get("vo", "")) != squash(beat.vo_line):
                continue
            body = m.group(2)
            for obj, d in objs:
                body = d.apply_plan(body, obj)
            html = html[:m.start(2)] + body + html[m.end(2):]
            break
    return html


def _set_attr(tag: str, key: str, value: str) -> str:
    """``<beat a="1">`` with ``key`` set to ``value`` (replaced if present)."""
    value = value.replace('"', "&quot;")
    pat = re.compile(rf'\s{re.escape(key)}="[^"]*"')
    if pat.search(tag):
        return pat.sub(f' {key}="{value}"', tag, count=1)
    return tag[:-1] + f' {key}="{value}">'


def _apply_cameras(html: str, scene: Scene) -> str:
    """The plan says where the eye goes (the story's discovery lines, a chapter's new setting):
    its view / zoom / focus / shot are the plan's, written on the beat whatever Agent 3 wrote; a
    shot Agent 3 chose stays when the plan names none."""
    for beat in scene.beats:
        cam = beat.camera or {}
        want = {}
        if cam.get("shot"):
            want["shot"] = str(cam["shot"])
        if cam.get("view"):
            want["view"] = str(cam["view"])
            if cam.get("zoom"):
                want["zoom"] = f'{float(cam["zoom"]):g}'
        if cam.get("focus"):
            focus = cam["focus"]
            want["focus"] = ", ".join(focus) if isinstance(focus, list) else str(focus)
        if not want:
            continue
        for m in re.finditer(r"<beat\b[^>]*>", html):
            if squash(attrs_of(m.group(0)[5:-1]).get("vo", "")) != squash(beat.vo_line):
                continue
            tag = m.group(0)
            for k, v in want.items():
                tag = _set_attr(tag, k, v)
            html = html[:m.start()] + tag + html[m.end():]
            break
    return html


def check_runtime(html: str, workdir: Path, scene_id: str, timeout: float = 240.0,
                  prelude_html: str | None = None) -> list[str]:
    """Lay out and play the scene headless. With ``prelude_html`` (the previous scene, as
    accepted) the scene is played the way it renders: opening on that scene's last frame."""
    workdir.mkdir(parents=True, exist_ok=True)
    path = workdir / f"stage-{scene_id}.html"
    path.write_text(html, encoding="utf-8")
    cmd = [sys.executable, "-m", "konvey.stage.check", str(path), themes.current().name]
    if prelude_html:
        prelude = workdir / f"stage-{scene_id}-prelude.html"
        prelude.write_text(prelude_html, encoding="utf-8")
        cmd.append(str(prelude))
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=str(REPO_ROOT))
    except subprocess.TimeoutExpired:
        return [f"stage check timed out after {timeout:.0f}s"]
    for line in reversed(proc.stdout.splitlines()):
        if line.startswith("STAGE_RESULT "):
            problems = json.loads(line[len("STAGE_RESULT "):])
            if problems and prelude_html:
                problems.append(continuity_note(prelude_html))
            return problems
    tail = (proc.stderr or proc.stdout).strip().splitlines()[-5:]
    return ["stage check crashed: " + " | ".join(tail)]


def last_beat_source(html: str) -> str:
    start = html.rfind("<beat ")
    start = html.rfind("<beat>") if start < 0 else start
    end = html.find("</beat>", start)
    return html[start:end + len("</beat>")] if start >= 0 and end >= 0 else ""


def continuity_note(prelude_html: str) -> str:
    return ("note: this scene was played the way it renders, opening on the previous scene's "
            "last beat (below). Its world actors carry over: actors with your tags take your ids "
            "in order; an id must keep the same tag across the cut (use a new id for a new kind "
            "of actor). Fix this scene, not the previous one.\n" + last_beat_source(prelude_html))


_BEAT_NO = re.compile(r"\bbeat (\d+)\b")


def _renumber(msg: str) -> str:
    """With a prelude, beat 0 is the previous scene's last frame; report this scene's own numbers."""
    def sub(m):
        n = int(m.group(1))
        return "the opening frame (previous scene's last beat)" if n == 0 else f"beat {n - 1}"
    return _BEAT_NO.sub(sub, msg)


def _run(html_path: str, theme: str = themes.DEFAULT, prelude: str = "") -> list[str]:
    """Subprocess side: play the scene with animations skipped and report errors."""
    problems = _play(html_path, theme, prelude)
    return [_renumber(p) for p in problems] if prelude else problems


def _play(html_path: str, theme: str, prelude: str) -> list[str]:
    import traceback

    from .scene import StageScene

    class _Check(StageScene):
        beats_file = html_path
        strict_layout = True

    _Check.theme = theme
    _Check.prelude_file = prelude

    try:
        _Check(skip_animations=True, file_writer_config={"write_to_movie": False}).run()
    except (BeatError, ValueError) as e:
        return [str(e)]
    except BaseException as e:  # noqa: BLE001 - everything goes back to Agent 3
        frames = traceback.extract_tb(e.__traceback__)
        where = next((f"{Path(f.filename).name}:{f.lineno}" for f in reversed(frames)
                      if "konvey/stage" in f.filename), "?")
        return [f"runtime error ({where}) -> {type(e).__name__}: {e}"]
    return []


if __name__ == "__main__":
    print("STAGE_RESULT " + json.dumps(_run(*sys.argv[1:4])), flush=True)
