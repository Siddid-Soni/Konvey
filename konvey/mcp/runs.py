"""Run directories for the Konvey MCP engine.

A run is a directory the harness owns: ``<workspace>/.konvey/runs/<run-id>/`` with
``run.json``, ``S1.html`` … ``S3.html`` and the engine's own scratch space under
``.engine/``. The harness edits the scene files with its normal file tools; this module
turns them into the wrappers ``konvey.render`` expects and keeps the run's state.

    from konvey.mcp.runs import new_run, load_run, write_engine_wrappers

    run = new_run("Where do facts live in an LLM?", workspace=".")
    write_engine_wrappers(run)          # .engine/agent3-S1.html + agent3-S1.py …

No manimgl, no agents, no network: importing this module only needs the stage theme.
"""

from __future__ import annotations

import json
import os
import re
import shutil
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

from ..stage import theme as themes

REPO_ROOT = Path(__file__).resolve().parents[2]
STATE_DIR = ".konvey"
RUNS_DIR = "runs"
SCENE_RE = re.compile(r"^S([1-9][0-9]*)$")
RUN_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
HEX_RE = re.compile(r"^#[0-9a-fA-F]{3}(?:[0-9a-fA-F]{3})?$")
MAX_SCENES = 3

WRAPPER = '''"""Generated by Konvey for {name}. Render: manimgl {name}.py SingleScene -w"""
import sys
from pathlib import Path

sys.path.insert(0, {root!r})
from konvey.stage.scene import StageScene  # noqa: E402


class SingleScene(StageScene):
    beats_file = str(Path(__file__).with_name("{beats}"))
    prelude_file = {prelude}
    theme = "{theme}"
    highlight = "{highlight}"
{fps}'''


SKELETON = "<beats>\n</beats>\n"


def now_iso() -> str:
    """UTC timestamp, second precision, ``Z`` suffix (sortable as a string)."""
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def atomic_write_json(path: str | Path, data: Any) -> Path:
    """Write JSON through a temp file, so a crash never leaves half a run.json."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(tmp, path)
    return path


def read_json(path: str | Path) -> Any:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def slugify(topic: str) -> str:
    """A short, path-safe slug for a topic (the run id adds the date)."""
    slug = re.sub(r"[^a-z0-9]+", "-", (topic or "").lower()).strip("-")
    slug = re.sub(r"-{2,}", "-", slug)[:40].strip("-")
    return slug or "video"


def workspace_root(workspace: str | Path | None = None) -> Path:
    """The project the runs belong to: explicit path, ``KONVEY_WORKSPACE``, else the cwd."""
    raw = workspace or os.environ.get("KONVEY_WORKSPACE") or Path.cwd()
    return Path(raw).expanduser().resolve()


def state_dir(workspace: str | Path | None = None) -> Path:
    return workspace_root(workspace) / STATE_DIR


def runs_dir(workspace: str | Path | None = None) -> Path:
    return state_dir(workspace) / RUNS_DIR


def ensure_state(workspace: str | Path | None = None) -> Path:
    """Create ``.konvey/`` and a self-ignoring ``.gitignore`` (never edits the project's own)."""
    root = state_dir(workspace)
    root.mkdir(parents=True, exist_ok=True)
    gitignore = root / ".gitignore"
    if not gitignore.exists():
        gitignore.write_text(f"{RUNS_DIR}/\n", encoding="utf-8")
    return root


def _check_highlight(theme: str, highlight: str | None) -> str | None:
    th = themes.get_theme(theme)
    if not highlight or not highlight.strip():
        return None
    value = highlight.strip()
    if HEX_RE.match(value):
        return value
    th.color(value)  # raises ValueError for an unknown name
    return value


def _validate_run_id(run_id: str) -> str:
    if not RUN_RE.match(run_id or ""):
        raise ValueError(f"invalid run id {run_id!r} (lowercase letters, digits and single hyphens)")
    return run_id


def _validate_scene_id(sid: str) -> str:
    if not SCENE_RE.match(sid or ""):
        raise ValueError(f"invalid scene id {sid!r} (S1, S2, …)")
    return sid


def _unique_dir(parent: Path, base: str) -> Path:
    candidate = parent / base
    if not candidate.exists():
        return candidate
    for n in range(2, 1000):
        candidate = parent / f"{base}-{n}"
        if not candidate.exists():
            return candidate
    raise RuntimeError(f"too many runs named {base!r}")


@dataclass
class Run:
    """One video run on disk. ``data`` is the parsed ``run.json``."""

    directory: Path
    data: dict

    @classmethod
    def from_dir(cls, directory: str | Path) -> "Run":
        directory = Path(directory).expanduser().resolve()
        run = cls(directory=directory, data=read_json(directory / "run.json"))
        run.validate()
        return run

    def validate(self) -> "Run":
        if not self.directory.is_dir():
            raise FileNotFoundError(f"run directory not found: {self.directory}")
        _validate_run_id(str(self.data.get("id", "")))
        if self.data["id"] != self.directory.name:
            raise ValueError(f"run.json id {self.data['id']!r} does not match its directory "
                             f"{self.directory.name!r}")
        try:
            seconds = float(self.data.get("duration_sec", 0))
        except (TypeError, ValueError):
            raise ValueError(f"run {self.data['id']}: duration_sec must be a number") from None
        if seconds <= 0:
            raise ValueError(f"run {self.data['id']}: duration_sec must be greater than zero")
        count = int(self.data.get("scene_count", 0))
        if not 1 <= count <= MAX_SCENES:
            raise ValueError(f"run {self.data['id']}: scene_count must be 1..{MAX_SCENES}, got {count}")
        scenes = self.data.get("scenes")
        if not isinstance(scenes, list) or len(scenes) != count:
            raise ValueError(f"run {self.data['id']}: scenes must list {count} scene(s)")
        ids = []
        for scene in scenes:
            if not isinstance(scene, dict) or "id" not in scene:
                raise ValueError(f"run {self.data['id']}: each scene needs an id")
            ids.append(_validate_scene_id(str(scene["id"])))
        if ids != [f"S{i}" for i in range(1, count + 1)]:
            raise ValueError(f"run {self.data['id']}: scenes must be S1..S{count}, got {ids}")
        themes.get_theme(str(self.data.get("theme", "")))
        _check_highlight(str(self.data["theme"]), self.data.get("highlight"))
        self.data.setdefault("status", "draft")
        self.data.setdefault("artifacts", {})
        self.data.setdefault("active_job", None)
        self.data.setdefault("created_at", now_iso())
        self.data.setdefault("updated_at", self.data["created_at"])
        return self

    def save(self) -> Path:
        self.data["updated_at"] = now_iso()
        return atomic_write_json(self.directory / "run.json", self.data)

    @property
    def id(self) -> str:
        return str(self.data["id"])

    @property
    def topic(self) -> str:
        return str(self.data.get("topic", ""))

    def scene_ids(self) -> list[str]:
        return [str(scene["id"]) for scene in self.data["scenes"]]

    def scene_path(self, sid: str) -> Path:
        _validate_scene_id(sid)
        if sid not in self.scene_ids():
            raise ValueError(f"run {self.id} has no scene {sid}")
        path = (self.directory / f"{sid}.html").resolve()
        if path.parent != self.directory:
            raise ValueError(f"scene {sid} resolves outside the run")
        return path

    def read_scene(self, sid: str) -> str:
        return self.scene_path(sid).read_text(encoding="utf-8")

    def engine_dir(self) -> Path:
        return self.directory / ".engine"

    def preview_dir(self) -> Path:
        return self.directory / "preview"

    def jobs_dir(self) -> Path:
        return self.directory / "jobs"

    def summary(self) -> dict:
        return {
            "id": self.id,
            "topic": self.topic,
            "status": self.data.get("status"),
            "created_at": self.data.get("created_at"),
            "updated_at": self.data.get("updated_at"),
            "scene_count": self.data.get("scene_count"),
            "duration_sec": self.data.get("duration_sec"),
            "directory": str(self.directory),
        }


def new_run(
    topic: str,
    workspace: str | Path | None = None,
    scenes: int = MAX_SCENES,
    duration: float = 90.0,
    theme: str = themes.DEFAULT,
    highlight: str | None = None,
    slug: str | None = None,
) -> Run:
    """Create a run directory with ``run.json`` and empty scene files.

    ``scenes`` is 1..3 (v1). ``theme`` and ``highlight`` are validated now, before any
    model or render work. A slug collision gets a ``-2``, ``-3`` … suffix.
    """
    topic = (topic or "").strip()
    if not topic:
        raise ValueError("topic is required")
    try:
        count = int(scenes)
    except (TypeError, ValueError):
        raise ValueError("scenes must be an integer") from None
    if not 1 <= count <= MAX_SCENES:
        raise ValueError(f"scenes must be 1..{MAX_SCENES}")
    try:
        seconds = float(duration)
    except (TypeError, ValueError):
        raise ValueError("duration must be a number") from None
    if seconds <= 0:
        raise ValueError("duration must be greater than zero")
    themes.get_theme(theme)
    highlight = _check_highlight(theme, highlight)

    root = ensure_state(workspace)
    parent = root / RUNS_DIR
    parent.mkdir(parents=True, exist_ok=True)
    base = _validate_run_id(slug) if slug else f"{now_iso()[:10]}-{slugify(topic)}"
    directory = _unique_dir(parent, base)
    directory.mkdir(parents=True)

    ids = [f"S{i}" for i in range(1, count + 1)]
    data: dict = {
        "id": directory.name,
        "topic": topic,
        "created_at": now_iso(),
        "updated_at": now_iso(),
        "scene_count": count,
        "duration_sec": seconds,
        "theme": theme,
        "highlight": highlight,
        "status": "draft",
        "scenes": [{"id": sid, "file": f"{sid}.html"} for sid in ids],
        "active_job": None,
        "artifacts": {},
    }
    run = Run(directory=directory, data=data)
    for sid in ids:
        run.scene_path(sid).write_text(SKELETON, encoding="utf-8")
    run.save()
    return run


def load_run(run_id: str, workspace: str | Path | None = None) -> Run:
    """Load a run by its id under ``<workspace>/.konvey/runs`` (never an arbitrary path)."""
    _validate_run_id(run_id)
    directory = runs_dir(workspace) / run_id
    if not directory.is_dir():
        raise FileNotFoundError(f"no run {run_id!r} in {runs_dir(workspace)}")
    return Run.from_dir(directory)


def list_runs(workspace: str | Path | None = None) -> list[dict]:
    """Every readable run in the workspace, newest first."""
    parent = runs_dir(workspace)
    if not parent.is_dir():
        return []
    out = []
    for directory in parent.iterdir():
        if not directory.is_dir() or not (directory / "run.json").is_file():
            continue
        try:
            out.append(Run.from_dir(directory).summary())
        except (OSError, ValueError, KeyError, json.JSONDecodeError):
            continue  # a half-written or hand-broken run must not hide the others
    return sorted(out, key=lambda r: r.get("created_at") or "", reverse=True)


def validate_scenes(run: Run, scenes: Iterable[str] | str | None = None) -> list[str]:
    """The requested scenes in run order; ``None`` means all of them."""
    all_ids = run.scene_ids()
    if scenes is None:
        return all_ids
    if isinstance(scenes, str):
        scenes = [scenes]
    wanted = {_validate_scene_id(str(sid).strip()) for sid in scenes if str(sid).strip()}
    if not wanted:
        raise ValueError("no scenes selected")
    unknown = wanted - set(all_ids)
    if unknown:
        raise ValueError(f"run {run.id} has no scene(s) {', '.join(sorted(unknown))}")
    return [sid for sid in all_ids if sid in wanted]


def write_engine_wrappers(run: Run, scenes: Iterable[str] | str | None = None,
                          fps: int | None = None) -> dict[str, Path]:
    """Copy the scene HTML into ``.engine/`` and write the wrappers ``konvey.render`` runs.

    Every scene gets a wrapper (so a subset still has its prelude chain); the return value
    names only the requested scenes. The prelude is the previous scene's HTML, which keeps
    the engine's continuity across a cut. ``fps`` records a frame rate in the wrapper; the
    stage sets ``camera.fps`` before ``setup`` so manimgl's timing and encoder both use it.
    """
    all_ids = run.scene_ids()
    wanted = validate_scenes(run, scenes)
    engine = run.engine_dir()
    engine.mkdir(parents=True, exist_ok=True)
    theme = str(run.data["theme"])
    highlight = run.data.get("highlight") or ""
    fps_line = ""
    if fps is not None:
        fps_line = f'    default_camera_config = {{"fps": {int(fps)}}}\n'
    for i, sid in enumerate(all_ids):
        source = run.scene_path(sid)
        if not source.is_file():
            raise FileNotFoundError(f"run {run.id}: scene {sid} is missing ({source})")
        shutil.copyfile(source, engine / f"agent3-{sid}.html")
        previous = all_ids[i - 1] if i else None
        prelude = (f'str(Path(__file__).with_name("agent3-{previous}.html"))'
                   if previous else '""')
        name = f"agent3-{sid}"
        (engine / f"{name}.py").write_text(
            WRAPPER.format(name=name, root=str(REPO_ROOT), beats=f"agent3-{sid}.html",
                           prelude=prelude, theme=theme, highlight=highlight,
                           fps=fps_line),
            encoding="utf-8",
        )
    return {sid: engine / f"agent3-{sid}.py" for sid in wanted}
